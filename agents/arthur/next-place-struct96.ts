// vesica r70, N dense — S is the last unclaimed seam, spatial equity).
// Face plane (local ±z, the figure plane) perpendicular to the S walking
// line: every walker gets the face-on fan read. BESIDE the line, never on
// it: procession drifts x 0→−7.3 (waystone→halt→mobius→ninesbridge); seat
// x∈[1.3,5.7] sits EAST of the whole procession, 3.3m+ clear (Bill's
// beside-the-line law).
// Yaw 0 (radians-on-the-wire). TRUE decoded envelope: local x −0.22..4.18,
// y 0..4.37, z ±0.79 → CENTER OFFSET cx 1.98, cz 0 (struct-80 law).
// Terrain 7pt: spread 7.4mm, lowest corner 0.0056 = PY.
// SAT: yaw-grown AABB vs census AABBs, BOTH sides center-offset corrected.
// Nearest standing: mosaic-0048 center 13.5m, ninesbridge center 15.8m
