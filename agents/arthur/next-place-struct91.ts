// (az0 r58) and foxden (az-8 r73.8, offline 10m+), face to the path at z=0:
// every walker gets the 3m face-on almond read. BESIDE the walking line
// (z=-3): hoop extremes z ±0.16 stay 2.84m off the line, furniture-class
// solid, no path obstruction (Bill's lamp law).
// Yaw 0 (radians-on-the-wire): build local +z (window face) → world +z.
// TRUE decoded envelope: local x ±2.715, y 0..3.68, z ±0.16 (build print
// bbox 5.43x3.68x0.32; symmetric, no center offset).
// Terrain 13pt probe: spread 2.1mm, mean PY -0.0435 (near-perfect flat).
// SAT: yaw-grown AABB vs census AABBs, BOTH sides center-offset corrected
// (struct-80 census-local-bbox law). Nearest standing entities ruledtower
// 12.4m, foxden 8.1m (derived; the gate below re-proves on FRESH live set).
