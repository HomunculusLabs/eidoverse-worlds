// NEW entity nx-struct-lemniscateseat (census-verified absent each run).
// Seat: (-60, -0.0237, -7) yaw Math.PI/2 — W spoke mid-gap station between
// stillwind (az270 r52) and screwwell (az270 r88), BESIDE the walking line
// (z=0): nearest ribbon point z=-2.83 (2.83m off line, beside-not-on law;
// steppable 0.46m heightfield), ∞ long axis on world z so both lobes face
// the W-ward walker (face-on ∞ at approach = the contract read).
// YAW DERIVATION: build local x = the ∞ long axis. At yaw π/2, local +x
// maps to world (cos(π/2), -sin(π/2)) = (0, -1) → long axis on world z.
// (Yaw sent as Math.PI/2 expression — radians-on-the-wire law, models.js:77.)
// TRUE decoded envelope: local x ±4.17, y 0..0.62, z ±1.66 (build print
// bbox 8.33x0.62x3.30; symmetric, no center offset).
// Terrain 11pt probe (next-terrain-struct90.ts @ CZ=-7): spread 9.5mm,
// corner-mean PY -0.0237 (E extreme floats 5.4mm, W embeds 4.1mm —
// stillwind-class absorbed by 0.46m section).
// SAT: yaw-grown AABB vs census AABBs, BOTH sides center-offset corrected
// (struct-80 census-local-bbox law). Nearest standing entity screwwell 28m
// (derived; the gate below re-proves on the FRESH live set).
